import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync, createReadStream, statSync } from 'node:fs';
import { execFile } from 'node:child_process';
import { promisify } from 'node:util';
import { createHash } from 'node:crypto';
import { createServer } from 'node:http';
import { validateExperimentalGenesis } from '@solana-classic/chain';

const exec = promisify(execFile);
const expected = '7TAUSfTzQeocodtVee2qsftsCYnJu2eCM1ALdADbHNon';
async function checksum(path: string) {
  const hash = createHash('sha256');
  for await (const chunk of createReadStream(path)) hash.update(chunk as Buffer);
  return hash.digest('hex');
}
export async function railwayOperation() {
  const mode = process.env.SC_OPERATION;
  if (!mode) return;
  if (process.env.SC_OP_ACK !== 'experimental-cold-recovery' || process.env.RAILWAY_PROJECT_ID !== '356bcb0b-49c4-4bd3-bf10-bff7db8f33fe' || process.env.RAILWAY_VOLUME_MOUNT_PATH !== '/data') throw new Error('Recovery requires the designated experimental project and explicit operator acknowledgement.');
  process.umask(0o077);
  if (mode === 'cold-restore') {
    if (process.env.RAILWAY_SERVICE_ID === 'd0a1de40-bd9c-47eb-a7fc-477f1c55b2d6') throw new Error('Live-service restore is forbidden.');
    if (existsSync('/data/ledger/genesis.bin') && existsSync('/data/network.json') && existsSync('/data/restore-receipt.json')) {
      const completed = JSON.parse(readFileSync('/data/restore-receipt.json', 'utf8')) as { archiveSha256: string; genesis: string };
      if (completed.genesis !== expected || completed.archiveSha256 !== process.env.SC_RESTORE_SHA256) throw new Error('Existing restore receipt mismatch.');
      return; // A normal restart preserves the already restored dataset.
    }
    if (existsSync('/data/ledger') || existsSync('/data/app') || existsSync('/data/operator') || existsSync('/data/network.json')) throw new Error('Restore requires a fresh isolated volume; never overwrite existing data.');
    if (readdirSync('/data').some(name => !['incoming', 'lost+found'].includes(name))) throw new Error('Unexpected isolated-volume contents.');
    const archive = '/data/incoming/current.tar';
    const digest = process.env.SC_RESTORE_SHA256;
    if (!digest || !/^[a-f0-9]{64}$/.test(digest) || statSync(archive).size > 10_000_000_000 || await checksum(archive) !== digest) throw new Error('Cold archive integrity mismatch.');
    // Only the archive generated by our stopped-writer backup is accepted.
    // Reject absolute/traversal paths and links before extraction.
    const inspect = await exec('python3', ['-c', 'import tarfile,pathlib,sys\nwith tarfile.open(sys.argv[1],"r:") as t:\n for m in t:\n  p=pathlib.PurePosixPath(m.name)\n  assert not p.is_absolute() and ".." not in p.parts and p.parts[0] in ["ledger","app","operator","network.json"]\n  assert m.isdir() or m.isfile()\nprint("Archive members validated")', archive], { timeout: 300_000, maxBuffer: 10_000 });
    if (!inspect.stdout.includes('validated')) throw new Error('Archive inspection failed.');
    const startedAt = new Date().toISOString();
    await exec('tar', ['--no-same-owner', '--no-same-permissions', '-xpf', archive, '-C', '/data'], { timeout: 300_000, maxBuffer: 64_000 });
    const config = JSON.parse(readFileSync('/data/network.json', 'utf8')) as { expectedGenesisHash: string };
    validateExperimentalGenesis(expected, config.expectedGenesisHash);
    writeFileSync('/data/restore-receipt.json', JSON.stringify({ startedAt, completedAt: new Date().toISOString(), archiveSha256: digest, genesis: expected, isolated: true, deploymentId: process.env.RAILWAY_DEPLOYMENT_ID, serviceId: process.env.RAILWAY_SERVICE_ID }) + '\n', { mode: 0o600, flag: 'wx' });
    console.log('Validated cold archive restored into the fresh isolated volume; original live volume untouched.');
    return;
  }
  if (mode !== 'cold-backup' || process.env.RAILWAY_SERVICE_ID !== 'd0a1de40-bd9c-47eb-a7fc-477f1c55b2d6') throw new Error('Unknown or wrong-source recovery operation.');
  for (const path of ['/data/ledger/genesis.bin', '/data/app', '/data/network.json', '/data/operator/bootstrap.json']) if (!existsSync(path)) throw new Error('Cold source dataset incomplete.');
  const config = JSON.parse(readFileSync('/data/network.json', 'utf8')) as { expectedGenesisHash: string };
  validateExperimentalGenesis(expected, config.expectedGenesisHash);
  mkdirSync('/data/backups', { recursive: true, mode: 0o700 });
  const archive = '/data/backups/current.tar';
  if (existsSync(archive)) throw new Error('Existing cold archive retained; use a reviewed new backup destination.');
  const startedAt = new Date().toISOString();
  // This fresh maintenance container never starts API/validator writers.
  await exec('tar', ['--sparse', '-cpf', archive, '-C', '/data', 'ledger', 'app', 'network.json', 'operator'], { timeout: 300_000, maxBuffer: 64_000 });
  const receipt = { schemaVersion: 1, scope: 'remote cold archive creation only; isolated restore pending', passed: true, genesis: expected, archiveSha256: await checksum(archive), archiveBytes: statSync(archive).size, startedAt, completedAt: new Date().toISOString(), deploymentId: process.env.RAILWAY_DEPLOYMENT_ID, serviceId: process.env.RAILWAY_SERVICE_ID, writerPolicy: 'Fresh maintenance container; neither validator nor API started.' };
  writeFileSync('/data/backups/receipt.json', JSON.stringify(receipt, null, 2) + '\n', { mode: 0o600, flag: 'wx' });
  console.log(JSON.stringify(receipt));
  const server = createServer((request, response) => {
    response.setHeader('Content-Type', 'application/json');
    response.statusCode = request.url === '/healthz' ? 200 : 503;
    response.end(JSON.stringify({ state: 'maintenance', message: 'Cold backup complete; test network writers are stopped.' }));
  });
  server.listen(3000, '0.0.0.0');
  await new Promise<void>(resolve => { for (const signal of ['SIGTERM', 'SIGINT'] as const) process.once(signal, () => { server.close(() => resolve()); }); });
  process.exit(0);
}
